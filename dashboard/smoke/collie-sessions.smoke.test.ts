import { join } from "node:path";
import { afterAll, beforeAll, expect, test } from "bun:test";
import { bootSmoke, evidencePath, gotoReady, mc, teardown, type Smoke } from "./harness";

let smoke: Smoke;
beforeAll(async () => { smoke = await bootSmoke(); await gotoReady(smoke); }, 60000);
afterAll(async () => { await teardown(smoke); });
const selected = () => smoke.page.locator('[data-testid="session-row"].selected').getAttribute("data-session");
const ready = () => smoke.page.waitForFunction(() => !(document.getElementById("send-body") as HTMLTextAreaElement)?.disabled);

test("Collie prepares one session and resumes an empty session after it expires", async () => {
  const { page } = smoke;
  await page.getByTestId("tab-collie").click();
  await ready();
  const id = await selected();
  expect(id).toBeTruthy();
  expect(await page.getByTestId("session-row").count()).toBe(1);
  await page.reload();
  await ready();
  expect(await selected()).toBe(id);
  expect(await page.getByTestId("session-row").count()).toBe(1);
  await page.getByTestId("tab-board").click();
  await mc(["collie", "end", id!, "--reason", "The session is idle."]);
  await page.getByTestId("tab-collie").click();
  await page.waitForFunction(() => document.querySelector('[data-testid="session-row"].selected')?.getAttribute("data-status") === "active" && document.getElementById("session-list")?.getAttribute("aria-busy") === "false");
  await ready();
  expect(await selected()).toBe(id);
  expect((await mc(["collie", "history", id!]) as { status: string }).status).toBe("active");
}, 30000);

test("conversation names show message excerpts and preserve an operator rename", async () => {
  const { page } = smoke;
  const id = await selected();
  const row = page.locator(`[data-session="${id}"]`);
  expect(await row.locator(".session-name").textContent()).toBe("New conversation");
  await page.getByTestId("send-body").fill("Compare two database options");
  await page.getByTestId("send").click();
  await page.waitForFunction(() => document.querySelector(".session-row.selected .session-name")?.textContent === "Compare two database options");
  const sessions = await mc(["collie", "list"]) as { sessions: { id: string; verb_allowlist: string[] }[] };
  const session = sessions.sessions.find(session => session.id === id)!;
  const identity = join(smoke.scratch, "title-agent.json");
  await Bun.write(identity, JSON.stringify({ run_id: id, tier: "collie", role: "collie", verb_allowlist: session.verb_allowlist }));
  await mc(["collie", "title", id!, "--title", "Compare database options"], { MC_RUN_JSON: identity });
  await page.waitForFunction(() => document.querySelector(".session-row.selected .session-name")?.textContent === "Compare database options");
  const options = row.locator("..").getByTestId("session-menu-button");
  await options.click();
  await page.getByRole("menuitem", { name: "Rename conversation", exact: true }).press("ArrowDown");
  expect(await page.getByRole("menuitem", { name: "Delete conversation", exact: true }).evaluate(node => document.activeElement === node)).toBe(true);
  await page.keyboard.press("ArrowUp");
  await page.keyboard.press("Enter");
  await page.getByTestId("session-rename-input").fill("Discard this name");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  expect(await row.locator(".session-name").textContent()).toBe("Compare database options");
  await options.click();
  await page.getByRole("menuitem", { name: "Rename conversation", exact: true }).click();
  await page.getByTestId("session-rename-input").fill("x".repeat(101));
  await page.getByTestId("session-rename-save").click();
  await page.getByRole("alert").filter({ hasText: "Use a name with 1 to 100 characters." }).waitFor();
  const title = "Database <options> & tradeoffs";
  await page.getByTestId("session-rename-input").fill(title);
  await page.route("**/api/sessions/*/title", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { message: "The test interrupts the rename." } }) }));
  await page.getByTestId("session-rename-save").click();
  await page.getByRole("alert").filter({ hasText: "The test interrupts the rename." }).waitFor();
  expect(await page.getByTestId("session-rename-input").inputValue()).toBe(title);
  await page.unroute("**/api/sessions/*/title");
  await page.getByTestId("session-rename-input").press("Enter");
  await page.getByTestId("session-rename-input").waitFor({ state: "detached" });
  expect(await row.locator(".session-name").textContent()).toBe(title);
  expect(await row.locator("options").count()).toBe(0);
  const retained = await mc(["collie", "title", id!, "--title", "Replace the user name"], { MC_RUN_JSON: identity }) as { title: string; changed: boolean };
  expect(retained.title).toBe(title);
  expect(retained.changed).toBe(false);
  await page.reload();
  await ready();
  expect(await selected()).toBe(id);
  expect(await row.locator(".session-name").textContent()).toBe(title);
  const history = await mc(["collie", "history", id!]) as { messages: { body: string }[] };
  expect(history.messages[0]?.body).toBe("Compare two database options");
  await page.setViewportSize({ width: 390, height: 844 });
  await options.click();
  await page.getByRole("menuitem", { name: "Rename conversation", exact: true }).click();
  await page.screenshot({ animations: "disabled", path: evidencePath("collie-conversation-rename-mobile.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
}, 60000);

test("conversation menus support cancellation, errors, deletion, and a fresh replacement", async () => {
  const { page } = smoke;
  const first = await selected();
  await page.getByTestId("new-session").click();
  await page.waitForFunction(id => document.querySelector('[data-testid="session-row"].selected')?.getAttribute("data-session") !== id, first);
  await ready();
  const second = await selected();
  await page.locator(`[data-session="${first}"]`).click({ button: "right" });
  await page.getByRole("menuitem",{ name: "Delete conversation", exact: true }).click();
  await page.getByRole("button",{ name: "Cancel", exact: true }).click();
  expect(await page.getByTestId("session-row").count()).toBe(2);
  expect(await selected()).toBe(second);
  const options = page.getByTestId("session-menu-button").first();
  await options.focus();
  await options.press("Enter");
  await page.getByRole("menuitem",{ name: "Delete conversation", exact: true }).waitFor();
  await page.keyboard.press("Escape");
  expect(await options.getAttribute("aria-expanded")).toBe("false");
  await options.press("Enter");
  await page.getByRole("menuitem",{ name: "Delete conversation", exact: true }).click();
  await page.route("**/api/sessions/*", async route => {
   if (route.request().method() === "DELETE") await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { message: "The test interrupts deletion." } }) });
   else await route.continue();
  });
  await page.getByTestId("session-delete-confirm").click();
  await page.getByRole("alert").filter({ hasText: "The test interrupts deletion." }).waitFor();
  expect(await page.getByTestId("session-row").count()).toBe(2);
  await page.unroute("**/api/sessions/*");
  await page.getByRole("button",{ name: "Cancel", exact: true }).click();
  // Delete the selected session through its ellipsis menu.
  await page.locator(`[data-session="${second}"]`).locator("..").getByTestId("session-menu-button").click();
  await page.screenshot({ animations: "disabled", path: evidencePath("collie-session-menu.png"), fullPage: true });
  await page.getByRole("menuitem",{ name: "Delete conversation", exact: true }).click();
  await page.getByTestId("session-delete-confirm").click();
  await page.locator(`[data-session="${second}"]`).waitFor({ state: "detached" });
  await ready();
  expect(await selected()).toBe(first);
  await page.reload();
  await ready();
  expect(await page.getByTestId("session-row").count()).toBe(1);
  expect(await selected()).toBe(first);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByTestId("session-menu-button").click();
  await page.getByRole("menuitem",{ name: "Delete conversation", exact: true }).click();
  await page.screenshot({ animations: "disabled", path: evidencePath("collie-session-delete-mobile.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByTestId("session-delete-confirm").click();
  await page.locator(`[data-session="${first}"]`).waitFor({ state: "detached" });
  await ready();
  expect(await selected()).not.toBe(first);
  expect(await page.getByTestId("session-row").count()).toBe(1);
  await page.getByTestId("send-body").fill("Ready immediately.");
  expect(await page.getByTestId("send-body").inputValue()).toBe("Ready immediately.");
  expect(smoke.browserLog.filter(line => line.startsWith("pageerror:"))).toEqual([]);
}, 60000);
